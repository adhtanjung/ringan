			<!-- Quick Create Modal -->
			<QuickCreateModal
				:is-open="showQuickCreate"
				:type="quickCreateType || 'problem_type'"
				@close="closeQuickCreate"
				@created="handleQuickCreateSuccess"
			/>
		</DialogContent>
	</Dialog>
</template>

<script setup lang="ts">
import { ref, computed, watch, reactive, nextTick } from "vue";
import { X, Loader2, Plus } from "lucide-vue-next";
import { useSupabase } from "@/composables/useSupabase";

// shadcn-vue components
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import {
	Select,
	SelectContent,
	SelectItem,
	SelectTrigger,
	SelectValue,
} from "@/components/ui/select";
import { Switch } from "@/components/ui/switch";
import { Badge } from "@/components/ui/badge";
import {
	Dialog,
	DialogContent,
	DialogDescription,
	DialogFooter,
	DialogHeader,
	DialogTitle,
} from "@/components/ui/dialog";
import QuickCreateModal from "@/components/admin/QuickCreateModal.vue";
import AsyncSearchSelect from "@/components/admin/AsyncSearchSelect.vue";
import FormFieldLabel from "@/components/admin/FormFieldLabel.vue";
import { getFormSchema } from "@/config/formSchemas";
import {
	generateActionId,
	generateSuggestionId,
} from "@/utils/commonIdGenerator";

// Migrated types
const USE_SUPABASE_FOR = [
	"problem_types",
	"problems",
	"assessments",
	"suggestions",
	"feedback_prompts",
	"next_actions",
	"training_examples",
];

// Supabase client
const { supabase } = useSupabase();

// Props
const props = defineProps({
	isOpen: {
		type: Boolean,
		default: false,
	},
	dataType: {
		type: String,
		required: true,
	},
	item: {
		type: Object,
		default: null,
	},
});

// Emits
const emit = defineEmits(["close", "save"]);

// Reactive data
const formData = reactive<Record<string, any>>({});
const jsonFields = reactive<Record<string, any>>({});
const jsonErrors = reactive<Record<string, any>>({});
const newTag = reactive<Record<string, any>>({});
const isSaving = ref(false);
const isGeneratingSystemId = ref(false);
const systemIdError = ref("");
const initialFormSnapshot = ref("");

// Validation state
const validationStatus = reactive<Record<string, any>>({
	type_name: { checked: false, exists: false, loading: false, error: "" },
	category_id: { checked: false, exists: false, loading: false, error: "" },
	sub_category_id: { checked: false, exists: false, loading: false, error: "" },
	question_id: { checked: false, exists: false, loading: false, error: "" },
});

const fieldTouched = reactive<Record<string, boolean>>({});
const hasAttemptedSave = ref(false);

// Dropdown options and quick create state
const dropdownOptions = reactive<Record<string, any>>({
	category: [] as any[],
	sub_category_id: [] as any[],
});
const showQuickCreate = ref(false);
const quickCreateType = ref<string | null>(null);
const quickCreateFieldKey = ref<string | null>(null);
const optionalSectionsOpen = reactive<Record<string, boolean>>({
	optional: false,
});

// Computed properties
const isEditing = computed(() => !!props.item);
const validationErrors = ref<string[]>([]);
const isValidationLoading = computed(() =>
	Object.values(validationStatus).some((status: any) => status.loading),
);

// Response type helpers (assessments)
const selectedResponseType = computed(() => formData.response_type);
const showScaleFields = computed(
	() =>
		props.dataType === "assessments" && selectedResponseType.value === "scale"
);

const dataTypeLabel = computed(() => {
	const labels: Record<string, string> = {
		problems: "Problem Category",
		assessments: "Assessment Question",
		suggestions: "Suggestion",
		feedback_prompts: "Feedback Prompt",
		next_actions: "Next Action",
		training_examples: "Fine-tuning Example",
		problem_types: "Problem Type",
	};
	return labels[props.dataType] || "Item";
});

const modalDescription = computed(() => {
	const content: Record<
		string,
		{ create: string; edit: string }
	> = {
		suggestions: {
			create:
				"Add therapeutic guidance linked to a subcategory so downstream prompts stay consistent.",
			edit: "Update therapeutic guidance text and linkage details.",
		},
		next_actions: {
			create:
				"Define what should happen next so workflow transitions stay predictable.",
			edit: "Update action behavior, naming, and operational details.",
		},
		feedback_prompts: {
			create:
				"Create a follow-up prompt to guide user responses after suggestions.",
			edit: "Update prompt wording and follow-up linkage.",
		},
	};

	const current = content[props.dataType];
	if (current) {
		return isEditing.value ? current.edit : current.create;
	}

	return isEditing.value ? "Update this record." : "Create a new record.";
});

const submitLabel = computed(() => {
	if (isEditing.value) {
		if (props.dataType === "suggestions") return "Save Suggestion";
		if (props.dataType === "next_actions") return "Save Action";
		return "Update";
	}

	if (props.dataType === "suggestions") return "Create Suggestion";
	if (props.dataType === "next_actions") return "Create Action";
	return "Create";
});

const showDefaultActiveNote = computed(
	() =>
		!isEditing.value &&
		(props.dataType === "suggestions" || props.dataType === "next_actions"),
);

const useSingleColumnLayout = computed(
	() =>
		!isEditing.value &&
		(props.dataType === "suggestions" || props.dataType === "next_actions"),
);

const formFields = computed(() => {
	return getFormSchema(props.dataType);
});

const isSubCategoryAsyncField = (field: { key: string }) =>
	field.key === "sub_category_id" &&
	(props.dataType === "assessments" || props.dataType === "suggestions");

const isAutoGeneratedIdField = (fieldKey: string) =>
	(props.dataType === "suggestions" && fieldKey === "suggestion_id") ||
	(props.dataType === "next_actions" && fieldKey === "action_id");

const isHiddenField = (field: { key: string }) => {
	// Keep create flow simple for system-managed fields.
	// IDs are auto-generated and is_active defaults to true.
	if (
		!isEditing.value &&
		(
			(props.dataType === "next_actions" &&
				(field.key === "action_id" || field.key === "is_active")) ||
			(props.dataType === "suggestions" &&
				(field.key === "suggestion_id" || field.key === "is_active"))
		)
	) {
		return true;
	}

	return false;
};

type FormSectionKey = "core" | "relationships" | "technical";
type ExtendedFormSectionKey = FormSectionKey | "optional";

const sectionDefinitions: Record<ExtendedFormSectionKey, { title: string }> = {
	core: {
		title: "Main information",
	},
	relationships: {
		title: "Linked records",
	},
	optional: {
		title: "Optional details",
	},
	technical: {
		title: "System details",
	},
};

const fieldDescriptions: Record<string, Record<string, string>> = {
	suggestions: {
		suggestion_id: "System-generated identifier for auditing and references.",
		sub_category_id:
			"Choose the subcategory this guidance belongs to.",
		cluster: "Optional grouping label for reporting or segmentation.",
		suggestion_text: "The therapeutic guidance text shown to users.",
		evidence_base: "Optional therapeutic model or evidence basis for this suggestion.",
		is_active: "Turn off to hide this suggestion from live workflows.",
	},
	next_actions: {
		action_id: "System-generated identifier for this action.",
		action_text: "Describe what operators or the system should do next.",
		is_active: "Turn off to prevent this action from being used.",
	},
};

const getFieldDescription = (fieldKey: string) =>
	fieldDescriptions[props.dataType]?.[fieldKey] || "";

const isOptionalField = (field: { key: string; type: string }) => {
	if (props.dataType === "suggestions") {
		return field.key === "cluster" || field.key === "evidence_base";
	}

	return false;
};

const isTechnicalField = (field: { key: string; type: string }) => {
	if (field.type === "json") return true;
	if (field.key === "is_active") return true;
	if (isAutoGeneratedIdField(field.key)) return true;

	if (props.dataType === "problem_types" && field.key === "category_id") return true;
	if (props.dataType === "suggestions" && field.key === "suggestion_id") return true;
	if (props.dataType === "assessments") {
		if (field.key === "question_id") return true;
		if (
			field.key === "scale_min" ||
			field.key === "scale_max" ||
			field.key.startsWith("scale_label_")
		) {
			return true;
		}
	}
	if (props.dataType === "feedback_prompts" && field.key === "prompt_id") return true;
	if (props.dataType === "next_actions" && field.key === "action_id") return true;
	if (props.dataType === "training_examples" && field.key === "example_id") return true;

	return false;
};

const isRelationshipField = (field: { key: string; type: string }) => {
	if (field.type === "select-with-create") return true;
	if (isSubCategoryAsyncField(field)) return true;
	if (props.dataType === "assessments" && field.key === "sub_category_id") return true;
	if (props.dataType === "feedback_prompts" && field.key === "next_action_id") return true;
	if (props.dataType === "problems" && field.key === "sub_category_id") return true;
	if (props.dataType === "problems" && field.key === "category") return true;

	return false;
};

const getFieldSection = (field: { key: string; type: string }) => {
	if (isOptionalField(field)) return "optional" as const;
	if (isTechnicalField(field)) return "technical" as const;
	if (isRelationshipField(field)) return "relationships" as const;
	return "core" as const;
};

const formSections = computed(() => {
	const buckets: Record<ExtendedFormSectionKey, any[]> = {
		core: [],
		relationships: [],
		optional: [],
		technical: [],
	};

	formFields.value.filter((field) => !isHiddenField(field)).forEach((field) => {
		buckets[getFieldSection(field)].push(field);
	});

	return (["core", "relationships", "optional", "technical"] as const)
		.map((key) => ({
			key,
			...sectionDefinitions[key],
			fields: buckets[key],
		}))
		.filter((section) => section.fields.length > 0);
});

const isOptionalSectionOpen = (sectionKey: string) =>
	Boolean(optionalSectionsOpen[sectionKey]);

const toggleOptionalSection = (sectionKey: string) => {
	optionalSectionsOpen[sectionKey] = !isOptionalSectionOpen(sectionKey);
};

