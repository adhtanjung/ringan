														<SelectValue :placeholder="'Select ' + field.label" />
													</SelectTrigger>
													<SelectContent>
														<SelectItem
															v-for="option in dropdownOptions[field.key]"
															:key="String(option[field.valueKey || 'value'])"
															:value="String(option[field.valueKey || 'value'])"
														>
															{{ option[field.labelKey || 'label'] }}
														</SelectItem>
													</SelectContent>
												</Select>
												<Button
													type="button"
													variant="outline"
													@click="openQuickCreate(field.createType || '', field.key)"
													:aria-label="`Create a new ${field.label}`"
													class="h-11 w-11 flex-shrink-0"
												>
													<Plus class="h-4 w-4" />
												</Button>
											</div>
										</div>

										<p
											v-if="needsValidation(field.key)"
											class="mt-1 text-sm leading-6"
											:class="getValidationTone(field.key)"
											role="status"
											aria-live="polite"
										>
											{{ getValidationMessage(field.key, field.label) }}
										</p>
									</div>
								</div>
							</div>

							<div
								v-if="validationErrors.length > 0"
								class="space-y-1 rounded-md border border-destructive/20 bg-destructive/5 px-3 py-2 text-sm leading-6 text-destructive"
							>
								<p class="font-medium">Please fix the following:</p>
								<ul class="list-disc space-y-1 pl-5">
									<li v-for="error in validationErrors" :key="error">
										{{ error }}
									</li>
								</ul>
							</div>
						</div>
					</div>

					<div
						class="sticky bottom-0 z-20 border-t bg-background/95 px-4 py-4 backdrop-blur supports-[backdrop-filter]:bg-background/80 sm:px-6"
					>
						<p
							v-if="showDefaultActiveNote"
							class="mb-2 text-xs leading-5 text-muted-foreground"
						>
							New records are active by default.
						</p>
						<DialogFooter class="flex flex-col-reverse gap-2 sm:flex-row sm:justify-end">
							<Button
								type="button"
								variant="outline"
								@click="closeModal"
								:disabled="isSaving"
								class="h-11 w-full sm:w-auto"
							>
								Cancel
							</Button>
								<Button
									type="submit"
									:disabled="isSaving || isValidationLoading || isGeneratingSystemId"
									class="h-11 w-full sm:min-w-[120px] sm:w-auto"
								>
								<Loader2 v-if="isSaving" class="mr-2 h-4 w-4 animate-spin" />
								{{ isSaving ? "Saving..." : submitLabel }}
							</Button>
						</DialogFooter>
					</div>
